#!/usr/bin/env node
/**
 * Release-gate check: the hand-written rules in .claude/CLAUDE.md must be committed.
 *
 * The file is two things at once. Above the REPOWISE markers are hand-written
 * repo rules — the architecture boundaries, the approval-gated path list, the
 * secrets rule. Below them, Repowise regenerates a codebase-intelligence index
 * on its own schedule, and it rewrites the file on every reindex, including the
 * commit hash it reports. That is not under anyone's review and not source.
 *
 * A blanket "the tree must be clean" gate therefore cannot be satisfied by any
 * developer who has repowise installed, so `make release-check` fails for
 * reasons that have nothing to do with the code being released. The obvious
 * escape — exempt the whole file from the clean-tree check — is worse: it would
 * also let someone edit the approval rules and ship that edit unreviewed.
 *
 * So this checks the difference instead. It fails if any *non-generated* part of
 * the file has uncommitted changes, and stays quiet when the only changes are
 * inside the auto-generated block. That is the property we actually care about:
 * rules are reviewed, index churn is not.
 *
 * Exit codes: 0 clean or generated-only, 1 hand-written rules are dirty.
 */

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

const FILE = ".claude/CLAUDE.md";
const START = "REPOWISE:START";
const END = "REPOWISE:END";

const text = readFileSync(FILE, "utf8");
const lines = text.split("\n");

const startIdx = lines.findIndex((l) => l.includes(START));
const endIdx = lines.findIndex((l) => l.includes(END));

if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error(`Release blocked: ${FILE} has no intact ${START}/${END} block.`);
  console.error(
    "Without those markers this check cannot tell hand-written rules from the generated index.",
  );
  console.error("Restore the markers rather than deleting them; do not silence this check.");
  process.exit(1);
}

const generatedLines = new Set();
for (let i = startIdx; i <= endIdx; i += 1) generatedLines.add(i + 1);

let diff;
try {
  diff = execFileSync("git", ["diff", "-U0", "--", FILE], { encoding: "utf8" });
} catch (error) {
  // No diff for this file at all — nothing to check.
  process.exit(0);
}

if (diff.trim() === "") {
  console.log(`Agent rules committed: ${FILE} has no uncommitted changes.`);
  process.exit(0);
}

// Parse @@ hunks: each changed line number, and whether it is an addition.
const offenders = [];
let currentLine = null;
for (const line of diff.split("\n")) {
  const hunk = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line);
  if (hunk) {
    currentLine = Number(hunk[1]);
    continue;
  }
  if (currentLine === null) continue;
  if (line.startsWith("+") && !line.startsWith("+++")) {
    if (!generatedLines.has(currentLine)) {
      offenders.push({ line: currentLine, text: line.slice(1) });
    }
    currentLine += 1;
  } else if (line.startsWith("-") && !line.startsWith("---")) {
    // A deletion shifts the target line; the block check below is a safety net.
    currentLine += 1;
  } else if (line.startsWith(" ")) {
    currentLine += 1;
  }
}

if (offenders.length > 0) {
  console.error(`Release blocked: ${FILE} has uncommitted HAND-WRITTEN rule changes.`);
  for (const o of offenders.slice(0, 10)) {
    console.error(`    line ${o.line}: ${o.text.slice(0, 100)}`);
  }
  console.error("Commit the rules before releasing.");
  console.error(
    `Changes inside the ${START} block are generated by Repowise and are ignored on purpose.`,
  );
  process.exit(1);
}

console.log(
  `Agent rules committed: ${FILE} differs only inside the generated Repowise block (ignored).`,
);
